#!/usr/bin/env python3
"""Local preview server for the RobinLab site + the private Hugging Face bucket.

Serves the static site in `root/` and implements the exact same JSON API contract
as the Cloudflare Pages Function in `functions/api/collection/[[path]].js`:

    GET /api/collection/files            -> JSON manifest of the bucket
    GET /api/collection/file?path=<enc>  -> streams one file's bytes (inline preview)
    POST /api/collection/share           -> mints a signed link valid for 30 minutes
    GET /api/collection/share?token=<t>  -> resolves that link back to one image
    GET /decks/<name>.pptx               -> public deck URL for the Office Web Viewer

That means the Collection page behaves identically locally and in production.
The Hugging Face token stays on the server; it is never sent to the browser.

On startup it mirrors `projects/` into `root/projects/` (the same copy Cloudflare
Pages gets from `tools/sync_projects.py`), so project links work locally too.

Usage:
    python dev_server.py                # http://localhost:5500
    python dev_server.py --port 8080
    python dev_server.py --dir root
    python dev_server.py --no-sync      # skip the projects/ mirror step

The token is read from, in order:
    1. the HF_TOKEN environment variable
    2. a `.dev.vars` file in the project root (lines of the form KEY=VALUE)

Nothing is hard-coded, and `.dev.vars` is git-ignored.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import hmac
import http.client
import json
import math
import os
import sys
import time
import urllib.parse
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer

BUCKET_ID = "robinlabdev/robinvault"
HF_HOST = "huggingface.co"
LISTING_TTL_S = 60
FILE_CACHE_SECONDS = 600

# How long a share link stays valid. The expiry is inside the signed payload, so
# editing the URL cannot extend it.
SHARE_TTL_SECONDS = 30 * 60

# Types the proxy will stream. Images power the Collection grid; .pptx decks are
# fetched by the presentations page and rendered client-side.
PPTX_TYPE = "application/vnd.openxmlformats-officedocument.presentationml.presentation"


def is_servable(content_type: str) -> bool:
    return content_type.startswith("image/") or content_type == PPTX_TYPE

# Reserved bucket prefix holding the small grid previews generated by
# `tools/make_thumbs.py`. They are served on request but never listed.
THUMB_PREFIX = "_thumbs/"

_listing_cache: dict[str, object] = {"at": 0.0, "files": None, "thumbs": None}


# --------------------------------------------------------------------------- #
# Token loading
# --------------------------------------------------------------------------- #
def load_var(project_root: str, name: str) -> str | None:
    """Read a setting from the environment, then from `.dev.vars`."""
    value = os.environ.get(name)
    if value:
        return value.strip()

    dev_vars = os.path.join(project_root, ".dev.vars")
    if os.path.isfile(dev_vars):
        with open(dev_vars, encoding="utf-8") as handle:
            for line in handle:
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                key, _, value = line.partition("=")
                if key.strip() == name:
                    return value.strip().strip("'\"") or None
    return None


def load_token(project_root: str) -> str | None:
    return load_var(project_root, "HF_TOKEN")


# --------------------------------------------------------------------------- #
# Share links (mirrors the Cloudflare Function exactly)
# --------------------------------------------------------------------------- #
def _b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def _iso_ms(ms: int) -> str:
    """Milliseconds since epoch -> `2026-10-21T12:00:00Z` (what JS Date parses)."""
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(ms / 1000))


def _b64url_decode(value: str) -> bytes:
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))


def create_share_token(secret: str, path: str, ttl_ms: int) -> str:
    """Token = base64url(payload) "." base64url(HMAC-SHA256(payload))."""
    payload = json.dumps({"p": path, "e": int(time.time() * 1000) + ttl_ms}, separators=(",", ":")).encode("utf-8")
    signature = hmac.new(secret.encode("utf-8"), payload, hashlib.sha256).digest()
    return f"{_b64url(payload)}.{_b64url(signature)}"


def read_share_token(secret: str, token: str) -> dict:
    """Returns {"path", "expiresAt"} or {"error": "share_invalid"|"share_expired"}."""
    payload_part, _, signature_part = token.partition(".")
    if not payload_part or not signature_part:
        return {"error": "share_invalid"}

    try:
        payload_bytes = _b64url_decode(payload_part)
        signature = _b64url_decode(signature_part)
    except (ValueError, TypeError):
        return {"error": "share_invalid"}

    expected = hmac.new(secret.encode("utf-8"), payload_bytes, hashlib.sha256).digest()
    if not hmac.compare_digest(expected, signature):
        return {"error": "share_invalid"}

    try:
        payload = json.loads(payload_bytes.decode("utf-8"))
    except (ValueError, UnicodeDecodeError):
        return {"error": "share_invalid"}

    if not isinstance(payload, dict) or not isinstance(payload.get("p"), str) or not isinstance(payload.get("e"), int):
        return {"error": "share_invalid"}
    if int(time.time() * 1000) >= payload["e"]:
        return {"error": "share_expired", "expiresAt": payload["e"]}
    return {"path": payload["p"], "expiresAt": payload["e"]}


# --------------------------------------------------------------------------- #
# Hugging Face helpers
# --------------------------------------------------------------------------- #
def _open(host: str, path: str, headers: dict[str, str] | None = None):
    conn = http.client.HTTPSConnection(host, timeout=60)
    conn.request("GET", path, headers=headers or {})
    return conn, conn.getresponse()


def get_listing(token: str) -> dict:
    """Return the cached listing: visible files plus the thumbnail index."""
    now = time.time()
    if _listing_cache["files"] and now - float(_listing_cache["at"]) < LISTING_TTL_S:
        return _listing_cache

    conn, resp = _open(
        HF_HOST,
        f"/api/buckets/{BUCKET_ID}/tree?recursive=true",
        {"Authorization": f"Bearer {token}", "Accept": "application/json"},
    )
    try:
        if resp.status != 200:
            raise RuntimeError(f"Bucket listing failed (HTTP {resp.status})")
        entries = json.loads(resp.read().decode("utf-8"))
    finally:
        conn.close()

    # Thumbnails live under `_thumbs/`. They are addressable by path but must not
    # show up as content, so they are indexed separately from the real files.
    thumbs: dict[str, dict] = {}
    for entry in entries:
        if entry.get("type") == "file" and entry["path"].startswith(THUMB_PREFIX):
            thumbs[entry["path"]] = {
                "path": entry["path"],
                "size": entry.get("size", 0),
                "contentType": entry.get("contentType") or "application/octet-stream",
            }

    files = []
    for entry in entries:
        if entry.get("type") != "file":
            continue
        path = entry["path"]
        if path.startswith(THUMB_PREFIX):
            continue
        slash = path.find("/")
        content_type = entry.get("contentType") or "application/octet-stream"
        thumb_path = f"{THUMB_PREFIX}{path}.webp"
        files.append(
            {
                "path": path,
                "name": path.rsplit("/", 1)[-1],
                "folder": "" if slash == -1 else path[:slash],
                "size": entry.get("size", 0),
                "contentType": content_type,
                "previewable": content_type.startswith("image/"),
                "uploadedAt": entry.get("uploadedAt"),
                # Set only when a generated preview exists; the client falls back
                # to the full-resolution original when it is None.
                "thumbPath": thumb_path if thumb_path in thumbs else None,
            }
        )
    files.sort(key=lambda item: item["path"])

    _listing_cache["at"] = now
    _listing_cache["files"] = files
    _listing_cache["thumbs"] = thumbs
    return _listing_cache


def open_file_stream(token: str, path: str):
    """Return (response_headers, connection, response) for a bucket file."""
    encoded = urllib.parse.quote(path, safe="")
    conn, resp = _open(
        HF_HOST,
        f"/buckets/{BUCKET_ID}/resolve/{encoded}",
        {"Authorization": f"Bearer {token}", "Accept": "*/*"},
    )

    # Private bucket -> 302 to a short-lived signed URL. Follow without the token.
    if resp.status in (301, 302, 303, 307, 308):
        location = resp.getheader("Location")
        conn.close()
        if not location:
            raise RuntimeError("Resolve returned a redirect with no target")
        parsed = urllib.parse.urlsplit(location)
        conn, resp = _open(parsed.netloc, urllib.parse.urlunsplit(("", "", parsed.path, parsed.query, "")))

    return conn, resp


# --------------------------------------------------------------------------- #
# Request handler
# --------------------------------------------------------------------------- #
class Handler(SimpleHTTPRequestHandler):
    token: str | None = None
    share_secret: str | None = None

    def log_message(self, fmt, *args):  # noqa: A003 - stdlib signature
        sys.stderr.write("  %s\n" % (fmt % args))

    # -- helpers ----------------------------------------------------------- #
    def _send_json(self, body: dict, status: int = 200, cache: str = "no-store") -> None:
        payload = json.dumps(body, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(payload)))
        self.send_header("Cache-Control", cache)
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(payload)

    def _not_configured(self) -> None:
        self._send_json(
            {
                "error": "not_configured",
                "message": "No HF_TOKEN found. Set the HF_TOKEN environment variable or create a .dev.vars file.",
            },
            500,
        )

    # -- routing ----------------------------------------------------------- #
    def _resolve_clean_url(self) -> None:
        """Map `/collection` -> `/collection.html`, matching Cloudflare Pages.

        Cloudflare serves extensionless URLs, so links use `/collection`. This
        keeps local preview consistent with production.
        """
        parsed = urllib.parse.urlsplit(self.path)
        path = parsed.path
        if path == "/" or path.endswith("/") or "." in path.rsplit("/", 1)[-1]:
            return
        target = os.path.join(self.directory, path.lstrip("/") + ".html")
        if os.path.isfile(target):
            self.path = path + ".html" + (f"?{parsed.query}" if parsed.query else "")

    def _handle_api(self, parsed: urllib.parse.SplitResult) -> bool:
        route = parsed.path.rstrip("/") or "/"

        # Public deck route used by the Office Web Viewer in production
        # (`functions/decks/[[path]].js`). Mirrored locally for parity.
        if route.startswith("/decks/"):
            if self.token is None:
                self._not_configured()
                return True
            name = urllib.parse.unquote(parsed.path[len("/decks/"):])
            self._serve_file("presentations/" + name, decks_only=True)
            return True

        if not route.startswith("/api/collection"):
            return False

        if self.token is None:
            self._not_configured()
            return True

        # Share links are the only writable endpoint: minting needs POST,
        # resolving needs GET.
        if route.endswith("/share"):
            self._serve_share(parsed)
            return True

        if self.command not in ("GET", "HEAD"):
            self._send_json({"error": "method_not_allowed"}, 405)
            return True

        if route.endswith("/file"):
            params = urllib.parse.parse_qs(parsed.query)
            self._serve_file((params.get("path") or [""])[0])
        else:
            self._serve_listing()
        return True

    # -- share links ------------------------------------------------------- #
    def _serve_share(self, parsed: urllib.parse.SplitResult) -> None:
        secret = self.share_secret
        if not secret:
            self._send_json(
                {
                    "error": "not_configured",
                    "message": "Set SHARE_SECRET (or HF_TOKEN) to enable share links.",
                },
                500,
            )
            return

        if self.command == "POST":
            self._create_share(secret)
        elif self.command in ("GET", "HEAD"):
            self._resolve_share(parsed, secret)
        else:
            self._send_json({"error": "method_not_allowed"}, 405)

    def _create_share(self, secret: str) -> None:
        try:
            length = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            length = 0
        try:
            body = json.loads(self.rfile.read(length).decode("utf-8") or "{}")
        except (ValueError, UnicodeDecodeError, OSError):
            body = {}

        path = body.get("path", "").strip() if isinstance(body, dict) and isinstance(body.get("path"), str) else ""
        if not path:
            self._send_json(
                {"error": "missing_path", "message": 'Send a JSON body like {"path":"wallpapers/foo.png"}.'},
                400,
            )
            return

        try:
            listing = get_listing(self.token or "")
        except Exception as err:  # noqa: BLE001
            self._send_json({"error": "upstream_error", "message": str(err)}, 502)
            return

        entry = next((file for file in listing["files"] if file["path"] == path), None)
        if entry is None:
            self._send_json({"error": "not_found", "message": "No such file in this bucket."}, 404)
            return
        if not entry["previewable"]:
            self._send_json({"error": "unsupported_type", "message": "Only images can be shared."}, 415)
            return

        ttl_ms = SHARE_TTL_SECONDS * 1000
        token = create_share_token(secret, entry["path"], ttl_ms)
        host = self.headers.get("Host") or "127.0.0.1:5500"

        self._send_json(
            {
                "token": token,
                "url": f"http://{host}/collection?share={urllib.parse.quote(token, safe='')}",
                "expiresAt": _iso_ms(int(time.time() * 1000) + ttl_ms),
                "ttlSeconds": SHARE_TTL_SECONDS,
            }
        )

    def _resolve_share(self, parsed: urllib.parse.SplitResult, secret: str) -> None:
        params = urllib.parse.parse_qs(parsed.query)
        token = (params.get("token") or [""])[0]
        if not token:
            self._send_json({"error": "missing_token", "message": "A `token` query parameter is required."}, 400)
            return

        read = read_share_token(secret, token)
        if read.get("error") == "share_expired":
            self._send_json(
                {"error": "share_expired", "message": "This shared link has expired. Shared links last 30 minutes."},
                410,
            )
            return
        if read.get("error"):
            self._send_json({"error": "share_invalid", "message": "This shared link is not valid."}, 403)
            return

        try:
            listing = get_listing(self.token or "")
        except Exception as err:  # noqa: BLE001
            self._send_json({"error": "upstream_error", "message": str(err)}, 502)
            return

        entry = next((file for file in listing["files"] if file["path"] == read["path"]), None)
        if entry is None:
            self._send_json(
                {"error": "not_found", "message": "That artwork is no longer in the collection."}, 404
            )
            return
        if not entry["previewable"]:
            self._send_json({"error": "unsupported_type", "message": "Only images can be shared."}, 415)
            return

        def url_for(path: str) -> str:
            return "/api/collection/file?path=" + urllib.parse.quote(path, safe="")

        thumb_path = entry["thumbPath"]
        self._send_json(
            {
                "path": entry["path"],
                "name": entry["name"],
                "folder": entry["folder"],
                "size": entry["size"],
                "contentType": entry["contentType"],
                "url": url_for(entry["path"]),
                "thumbUrl": url_for(thumb_path) if thumb_path else None,
                "expiresAt": _iso_ms(read["expiresAt"]),
                "secondsLeft": max(0, math.ceil((read["expiresAt"] - time.time() * 1000) / 1000)),
            }
        )

    def _serve_listing(self) -> None:
        try:
            listing = get_listing(self.token or "")
        except Exception as err:  # noqa: BLE001 - surface any upstream failure as JSON
            self._send_json({"error": "upstream_error", "message": str(err)}, 502)
            return

        files = listing["files"]
        folders = sorted({file["folder"] for file in files})

        def url_for(path: str) -> str:
            return "/api/collection/file?path=" + urllib.parse.quote(path, safe="")

        self._send_json(
            {
                "bucket": BUCKET_ID,
                "count": len(files),
                "totalSize": sum(file["size"] for file in files),
                "folders": folders,
                "files": [
                    {
                        **{key: value for key, value in file.items() if key != "thumbPath"},
                        "url": url_for(file["path"]),
                        # Lightweight grid preview; None means "use `url`".
                        "thumbUrl": url_for(file["thumbPath"]) if file["thumbPath"] else None,
                    }
                    for file in files
                ],
            },
            200,
            cache="public, max-age=60",
        )

    def _serve_file(self, path: str, decks_only: bool = False) -> None:
        if not path:
            self._send_json({"error": "missing_path", "message": "A `path` query parameter is required."}, 400)
            return

        try:
            listing = get_listing(self.token or "")
        except Exception as err:  # noqa: BLE001
            self._send_json({"error": "upstream_error", "message": str(err)}, 502)
            return

        # Generated thumbnails are valid targets too, but stay out of the listing.
        entry = next((file for file in listing["files"] if file["path"] == path), None)
        if entry is None:
            entry = listing["thumbs"].get(path)
        if entry is None:
            self._send_json({"error": "not_found", "message": "No such file in this bucket."}, 404)
            return
        if not is_servable(entry["contentType"]) or (decks_only and entry["contentType"] != PPTX_TYPE):
            self._send_json({"error": "unsupported_type", "message": "Only images and PowerPoint decks can be served."}, 415)
            return

        try:
            conn, resp = open_file_stream(self.token or "", path)
        except Exception as err:  # noqa: BLE001
            self._send_json({"error": "upstream_error", "message": str(err)}, 502)
            return

        try:
            if resp.status != 200:
                self._send_json({"error": "upstream_error", "message": f"Resolve failed (HTTP {resp.status})"}, 502)
                return

            length = resp.getheader("Content-Length")
            self.send_response(200)
            self.send_header("Content-Type", resp.getheader("Content-Type") or entry["contentType"])
            self.send_header("Content-Disposition", "inline")
            self.send_header("Cache-Control", f"public, max-age={FILE_CACHE_SECONDS}")
            self.send_header("X-Content-Type-Options", "nosniff")
            if length:
                self.send_header("Content-Length", length)
            self.end_headers()

            if self.command == "HEAD":
                return
            while True:
                chunk = resp.read(64 * 1024)
                if not chunk:
                    break
                self.wfile.write(chunk)
        finally:
            conn.close()

    # -- entry points ------------------------------------------------------ #
    def do_GET(self):  # noqa: N802 - stdlib naming
        parsed = urllib.parse.urlsplit(self.path)
        if self._handle_api(parsed):
            return
        self._resolve_clean_url()
        super().do_GET()

    def do_HEAD(self):  # noqa: N802 - stdlib naming
        parsed = urllib.parse.urlsplit(self.path)
        if self._handle_api(parsed):
            return
        self._resolve_clean_url()
        super().do_HEAD()

    def do_POST(self):  # noqa: N802 - stdlib naming
        parsed = urllib.parse.urlsplit(self.path)
        if self._handle_api(parsed):
            return
        self._send_json({"error": "method_not_allowed"}, 405)


# --------------------------------------------------------------------------- #
# Entry point
# --------------------------------------------------------------------------- #
def main() -> int:
    project_root = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=5500)
    parser.add_argument("--dir", default=os.path.join(project_root, "root"))
    parser.add_argument(
        "--no-sync",
        action="store_true",
        help="skip mirroring projects/ into root/projects/ before serving",
    )
    args = parser.parse_args()

    if not os.path.isdir(args.dir):
        print(f"error: static directory not found: {args.dir}", file=sys.stderr)
        return 1

    if not args.no_sync:
        # Same mirror Cloudflare Pages runs as its build command, so local
        # /projects/... links behave exactly like production.
        sys.path.insert(0, os.path.join(project_root, "tools"))
        import sync_projects  # noqa: PLC0415 - local tool, imported lazily

        copied, removed, unchanged = sync_projects.sync()
        if copied or removed:
            print(f"projects: synced {copied} copied, {removed} removed, {unchanged} unchanged")
        else:
            print(f"projects: up to date ({unchanged} files)")

    Handler.directory = os.path.abspath(args.dir)
    Handler.token = load_token(project_root)
    # Prefer a dedicated secret so links survive a token rotation; the HF token
    # is a safe local fallback (both stay server-side).
    Handler.share_secret = load_var(project_root, "SHARE_SECRET") or Handler.token

    # Pass `directory` explicitly: SimpleHTTPRequestHandler resets it to the CWD
    # when the argument is omitted, which would ignore --dir.
    handler = partial(Handler, directory=Handler.directory)

    if Handler.token:
        print("HF_TOKEN: loaded (bucket requests will be proxied server-side)")
    else:
        print("HF_TOKEN: NOT FOUND - the Collection page will show a setup message.")
        print("           Create a .dev.vars file with:  HF_TOKEN=hf_xxx")
        print("           Or set the env var:            $env:HF_TOKEN = 'hf_xxx'")

    server = ThreadingHTTPServer((args.host, args.port), handler)
    print(f"Serving {Handler.directory}")
    print(f"  Site:       http://{args.host}:{args.port}/")
    print(f"  Collection: http://{args.host}:{args.port}/collection.html")
    print("Press Ctrl+C to stop.")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopped.")
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
