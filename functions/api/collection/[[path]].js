/**
 * Hugging Face bucket proxy — Cloudflare Pages Function.
 *
 * Endpoints (this single catch-all file serves all of them):
 *   GET  /api/collection/files            -> JSON manifest of the private bucket
 *   GET  /api/collection/file?path=<enc>  -> streams one file's bytes (inline, view-only)
 *   POST /api/collection/share            -> mints a signed link valid for 30 minutes
 *   GET  /api/collection/share?token=<t>  -> resolves that link back to one image
 *
 * The Hugging Face access token never reaches the browser. It is read from the
 * `HF_TOKEN` secret (Pages -> Settings -> Environment variables) and used only
 * for server-to-server calls.
 *
 * The bucket is private, so the upstream `resolve` endpoint answers with a 302 to
 * a short-lived signed CDN URL. We follow that redirect ourselves so the token is
 * sent to huggingface.co only, never to the CDN.
 *
 * The manifest also carries a `thumbUrl` for each file. Those point at the small
 * WebP previews that `tools/make_thumbs.py` stores under the reserved `_thumbs/`
 * prefix, so the grid does not have to download full-resolution originals.
 */

const BUCKET_ID = "robinlabdev/robinvault";
const HF = "https://huggingface.co";

// Types the proxy is willing to stream to the browser. Images power the
// Collection grid; .pptx decks are handed to the Office Web Viewer (see
// `functions/decks/[[path]].js`), which fetches the file from a public URL.
export const PPTX_TYPE = "application/vnd.openxmlformats-officedocument.presentationml.presentation";

function isServable(contentType) {
  return contentType.startsWith("image/") || contentType === PPTX_TYPE;
}

// How long a cached bucket listing stays valid (ms). Keeps browsing snappy and
// avoids hammering the Hub on every image request.
const LISTING_TTL_MS = 60_000;

// Browser/CDN cache lifetime for image bytes (seconds). Files in the vault are
// immutable, so this can be generous.
const FILE_CACHE_SECONDS = 600;

// Generated previews never change for a given path, so cache them for a year.
const THUMB_CACHE_SECONDS = 31_536_000;

// Reserved bucket prefix holding the small grid previews generated by
// `tools/make_thumbs.py`. They are served on request but never listed in the
// collection itself, so the grid and its folder counts stay about real files.
const THUMB_PREFIX = "_thumbs/";

// How long a share link stays valid. Enforced on the server: the expiry is part
// of the signed payload, so editing the URL cannot extend it.
const SHARE_TTL_SECONDS = 30 * 60;

// Module-level cache. Cloudflare reuses isolates, so this is effective in practice.
let listingCache = { at: 0, files: null, thumbs: null };

/** Same-origin proxy URL for a bucket path. */
const fileUrl = (path) => `/api/collection/file?path=${encodeURIComponent(path)}`;

