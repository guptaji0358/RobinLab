/* Share links                                                                */
/* -------------------------------------------------------------------------- */

const shareEncoder = new TextEncoder();
const shareDecoder = new TextDecoder();

/** base64url without padding, so the token survives being pasted in a URL. */
function b64urlEncode(bytes) {
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

function b64urlDecode(value) {
  const padded = value.replace(/-/g, "+").replace(/_/g, "/");
  const binary = atob(padded + "=".repeat((4 - (padded.length % 4)) % 4));
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

/**
 * The HMAC key. `SHARE_SECRET` is preferred so links survive a token rotation;
 * `HF_TOKEN` is the fallback so the feature works without extra configuration.
 */
function shareSecret(env) {
  return env.SHARE_SECRET || env.HF_TOKEN || null;
}

function shareKey(secret) {
  return crypto.subtle.importKey("raw", shareEncoder.encode(secret), { name: "HMAC", hash: "SHA-256" }, false, [
    "sign",
    "verify",
  ]);
}

/** Token = base64url(payload) "." base64url(HMAC-SHA256(payload)), payload = {p, e}. */
async function createShareToken(secret, path, ttlMs) {
  const payload = shareEncoder.encode(JSON.stringify({ p: path, e: Date.now() + ttlMs }));
  const signature = await crypto.subtle.sign("HMAC", await shareKey(secret), payload);
  return `${b64urlEncode(payload)}.${b64urlEncode(new Uint8Array(signature))}`;
}

/**
 * Verify a token. Returns `{ path, expiresAt }` on success, or `{ error }` where
 * error is `share_invalid` (bad signature / malformed) or `share_expired`.
 */
async function readShareToken(secret, token) {
  const dot = token.indexOf(".");
  if (dot < 1 || dot === token.length - 1) return { error: "share_invalid" };

  let payloadBytes;
  let signature;
  try {
    payloadBytes = b64urlDecode(token.slice(0, dot));
    signature = b64urlDecode(token.slice(dot + 1));
  } catch {
    return { error: "share_invalid" };
  }

  // `verify` compares in constant time, so a forged signature cannot be probed.
  let valid = false;
  try {
    valid = await crypto.subtle.verify("HMAC", await shareKey(secret), signature, payloadBytes);
  } catch {
    valid = false;
  }
  if (!valid) return { error: "share_invalid" };

  let payload;
  try {
    payload = JSON.parse(shareDecoder.decode(payloadBytes));
  } catch {
    return { error: "share_invalid" };
  }

  if (!payload || typeof payload.p !== "string" || typeof payload.e !== "number") {
    return { error: "share_invalid" };
  }
  if (Date.now() >= payload.e) return { error: "share_expired", expiresAt: payload.e };

  return { path: payload.p, expiresAt: payload.e };
}

function json(body, status = 200, extraHeaders = {}) {
  return new Response(JSON.stringify(body), {
    status,
    headers: {
      "Content-Type": "application/json; charset=utf-8",
      "Cache-Control": "no-store",
      ...extraHeaders,
    },
  });
}

/** Fetch (and cache) the bucket listing: the visible files plus the thumbnail index. */
async function getListing(token) {
  const now = Date.now();
  if (listingCache.files && now - listingCache.at < LISTING_TTL_MS) {
    return listingCache;
  }

  const res = await fetch(`${HF}/api/buckets/${BUCKET_ID}/tree?recursive=true`, {
    headers: { Authorization: `Bearer ${token}` },
  });
  if (!res.ok) {
    throw new Error(`Bucket listing failed (HTTP ${res.status})`);
  }

  const entries = await res.json();

  // Thumbnails live under `_thumbs/`. They are addressable by path but must not
  // show up as content, so they are indexed separately from the real files.
  const thumbs = new Map();
  for (const entry of entries) {
    if (entry.type === "file" && entry.path.startsWith(THUMB_PREFIX)) {
      thumbs.set(entry.path, entry);
    }
  }

  const files = entries
    .filter((entry) => entry.type === "file" && !entry.path.startsWith(THUMB_PREFIX))
    .map((entry) => {
      const slash = entry.path.lastIndexOf("/");
      const contentType = entry.contentType || "application/octet-stream";
      const thumbPath = `${THUMB_PREFIX}${entry.path}.webp`;
      return {
        path: entry.path,
        name: slash === -1 ? entry.path : entry.path.slice(slash + 1),
        folder: slash === -1 ? "" : entry.path.slice(0, slash),
        size: entry.size,
        contentType,
        // Browsers can render images inline; anything else cannot be previewed here.
        previewable: contentType.startsWith("image/"),
        uploadedAt: entry.uploadedAt || null,
        // Set only when a generated preview actually exists for this file. The
        // client falls back to the full-resolution original when it is null.
        thumbPath: thumbs.has(thumbPath) ? thumbPath : null,
      };
    })
    .sort((a, b) => a.path.localeCompare(b.path));

  listingCache = { at: now, files, thumbs };
  return listingCache;
}

function requireToken(env) {
  const token = env.HF_TOKEN;
  if (!token) {
    return json(
      {
        error: "not_configured",
        message:
          "The HF_TOKEN secret is not set for this deployment. Add it in your host's environment variables and redeploy.",
      },
      500,
    );
  }
  return null;
}

async function handleList(env) {
  const missing = requireToken(env);
  if (missing) return missing;

  try {
    const { files } = await getListing(env.HF_TOKEN);
    const folders = [...new Set(files.map((file) => file.folder))].sort((a, b) => a.localeCompare(b));

    return json(
      {
        bucket: BUCKET_ID,
        count: files.length,
        totalSize: files.reduce((sum, file) => sum + file.size, 0),
        folders,
        files: files.map(({ thumbPath, ...file }) => ({
          ...file,
          url: fileUrl(file.path),
          // Lightweight grid preview; null means "use `url`" (see collection.js).
          thumbUrl: thumbPath ? fileUrl(thumbPath) : null,
        })),
      },
      200,
      { "Cache-Control": "public, max-age=60, stale-while-revalidate=600" },
    );
  } catch (err) {
    return json({ error: "upstream_error", message: String(err?.message || err) }, 502);
  }
}

/**
 * Stream one bucket file, but only if it exists in the bucket listing.
 *
 * `allow` narrows what a given route may expose: the Collection endpoint accepts
 * images and decks, while `/decks/*` serves PowerPoint files only.
 */
export async function streamBucketFile(env, request, path, { allow = (entry) => isServable(entry.contentType) } = {}) {
  const missing = requireToken(env);
  if (missing) return missing;

  if (!path) return json({ error: "missing_path", message: "A file path is required." }, 400);

  // Only serve files that actually exist in the bucket. The listing also tells us
  // the true content type, so a crafted `path` cannot pull arbitrary content.
  // Generated thumbnails are valid targets too, but stay out of the listing.
  let entry;
  try {
    const { files, thumbs } = await getListing(env.HF_TOKEN);
    entry = files.find((file) => file.path === path) || thumbs.get(path);
  } catch (err) {
    return json({ error: "upstream_error", message: String(err?.message || err) }, 502);
  }

  if (!entry) return json({ error: "not_found", message: "No such file in this bucket." }, 404);
  if (!allow(entry)) {
    return json({ error: "unsupported_type", message: "Only images and PowerPoint decks can be served." }, 415);
  }

  // `encodeURIComponent` encodes "/" as %2F, which the Hub's resolve route accepts.
  const resolveUrl = `${HF}/buckets/${BUCKET_ID}/resolve/${encodeURIComponent(path)}`;

  let upstream = await fetch(resolveUrl, {
    headers: { Authorization: `Bearer ${env.HF_TOKEN}` },
    redirect: "manual",
  });

  // Private buckets answer 302 -> signed CDN URL. Follow it without the token.
  if (upstream.status >= 300 && upstream.status < 400) {
    const location = upstream.headers.get("Location");
    if (!location) {
      return json({ error: "upstream_error", message: "Resolve returned a redirect with no target." }, 502);
    }
    upstream = await fetch(location);
  }

  if (!upstream.ok) {
    return json({ error: "upstream_error", message: `Resolve failed (HTTP ${upstream.status})` }, 502);
  }

  const headers = new Headers({
    "Content-Type": upstream.headers.get("Content-Type") || entry.contentType,
    // `inline` (never `attachment`) keeps the browser previewing instead of saving.
    "Content-Disposition": "inline",
    "Cache-Control": `public, max-age=${FILE_CACHE_SECONDS}`,
    "X-Content-Type-Options": "nosniff",
  });
  const length = upstream.headers.get("Content-Length");
  if (length) headers.set("Content-Length", length);

  if (request.method === "HEAD") return new Response(null, { status: 200, headers });
  return new Response(upstream.body, { status: 200, headers });
}

/**
 * Serve one file through Cloudflare's edge cache. A hit skips the bucket listing
 * and both Hugging Face round trips, which is most of the latency of a grid card.
 * Thumbnails are generated once per file, so they are cached for a year.
 */
async function handleFile(env, request, url, ctx) {
  const path = url.searchParams.get("path");
  const isThumb = !!path && path.startsWith(THUMB_PREFIX);
  const cache = typeof caches !== "undefined" ? caches.default : null;
  const cacheKey = new Request(url.toString(), { method: "GET" });

  if (cache && request.method === "GET") {
    const hit = await cache.match(cacheKey);
    if (hit) return hit;
  }

  const response = await streamBucketFile(env, request, path);

  if (isThumb && response.ok) {
    const headers = new Headers(response.headers);
    headers.set("Cache-Control", `public, max-age=${THUMB_CACHE_SECONDS}, immutable`);
    const cached = new Response(response.body, { status: response.status, headers });
    if (cache && request.method === "GET") {
      const copy = cached.clone();
      if (ctx && ctx.waitUntil) ctx.waitUntil(cache.put(cacheKey, copy));
      else await cache.put(cacheKey, copy);
    }
    return cached;
  }

  return response;
}

